import type { AssetSourceEntry } from './sources'

const sound = (
  cue: string,
  remoteId: string,
  clips: [number, number][],
  purpose: string,
  loop = false,
): AssetSourceEntry => ({
  id: `sound_${loop ? 'loop_' : ''}${cue}`,
  kind: 'sound',
  source: 'freesound',
  remoteId,
  tier: 'small',
  group: 'flat47',
  license: 'CC0-1.0',
  purpose,
  sound: {
    cue,
    loop,
    clips: clips.map(([start, duration]) => ({ start, duration })),
    ...(cue === 'neighbour' ? { highpassHz: 120, lowpassHz: 380 } : {}),
    ...(cue === 'wind' ? { highpassHz: 70, lowpassHz: 2500 } : {}),
    ...(cue === 'whisper' ? { highpassHz: 100, lowpassHz: 1600 } : {}),
    ...(cue === 'static' ? { highpassHz: 100, lowpassHz: 4500 } : {}),
    ...(cue === 'cough' ? { highpassHz: 300, lowpassHz: 3200 } : {}),
    ...(cue === 'traffic' ? { highpassHz: 60, lowpassHz: 1600 } : {}),
    ...(cue === 'clock' ? { repeat: { every: 1, count: 4 } } : {}),
  },
})

